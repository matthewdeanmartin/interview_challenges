# Longest Substring Without Repeating Characters Difficulty: Medium
# Given a string s, find the length of the longest substring without repeating characters.

# Example: Input: "abcabcbb" 
# Output: 3 (The answer is "abc")

# Once you solve this, some companies often extend the problem to further test your thinking:

# Extension 1: What if the string is very large (millions of characters)? How would you optimize your solution to handle that efficiently?

# Extension 2: Now, modify the problem: Find the longest substring where at most k characters can repeat. How would you solve that?
